"""Gym benchmark publish boundary converter (E1 process boundary; NFR-2: the rsi core does not touch the Gym directory).

stdin : benchmark artifact payload JSON (rsi.ops.benchmark_synthesis.
        GymBenchmarkPackage.as_dict(): {name, items, taskset_items, manifest})
stdout: {"written": [...], "benchmark", "version", "item_count", ...} JSON

Writes (idempotent: re-running the same input produces identical bytes):
  benchmarks/<name>/data/<name>_v<version>.jsonl   complete items (including info lineage)
  benchmarks/<name>/data/<name>_benchmark.jsonl    canonical 3-field rows (via prepare.py)
  benchmarks/<name>/config.yaml                    dataset attach + generic prompt
  benchmarks/<name>/prepare.py                     idempotent script that reads data directly
  eval_service/profiles/rsi_v0_<name>.yaml         BenchmarkSpec registration

Usage:
  cat benchmark_payload.json | python3 scripts/gym_publish_benchmark.py \
      --gym-root "$GYM_ROOT" --version 1

Evaluation chain notes (current scope): config/profile are structural mount points (dataset + generic
prompt + BenchmarkSpec registration); the real `gym eval run` evaluation chain will be wired next period -- the
resources_server reference in config is a placeholder and must be filled according to the Gym resource stack before loading.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List

_GYM_ITEM_FIELDS = ("question", "expected_answer", "reference_solution")


def _safe_name(name: str) -> str:
    sanitized = re.sub(r"[^a-zA-Z0-9_-]+", "-", name).strip("-").lower()
    if not sanitized:
        raise ValueError(f"benchmark name {name!r} is empty after sanitization and cannot be used as a directory name")
    return sanitized


def _write(path: Path, text: str, written: List[str], gym_root: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    written.append(str(path.relative_to(gym_root)).replace("\\", "/"))


def _config_yaml(name: str, version: int) -> str:
    return f"""# {name} benchmark — materialized from ADF RSI trajectory synthesis.
# GENERATED by ADF scripts/gym_publish_benchmark.py — regenerate, do not hand-edit.
# Structural attach point (dataset + generic prompt), modeled on
# benchmarks/gsm8k/config_dsh.yaml. NOTE: the Gym eval chain (`gym eval run`)
# is wired in a later phase; the resources_server reference below is a
# placeholder and must be resolved against the Gym resource stack before loading.
config_paths: []

{name}_dsh_agent:
  responses_api_agents:
    dsh_agent:
      entrypoint: app.py
      resources_server:
        type: resources_servers
        name: {name}_resources  # placeholder — eval chain wiring is a later phase
      concurrency: 4
      timeout: 600
      datasets:
      - name: {name}
        type: benchmark
        jsonl_fpath: benchmarks/{name}/data/{name}_v{version}.jsonl
        prompt_config: benchmarks/prompts/generic/default.yaml
        prepare_script: benchmarks/{name}/prepare.py
"""


_PREPARE_TEMPLATE = '''"""Idempotent prepare for the __NAME__ benchmark (ADF RSI trajectory synthesis).

Reads the versioned data file written by the ADF publisher and materializes
the canonical Gym JSONL (question / expected_answer / reference_solution).
No network access — provenance (lessons / cluster labels / fingerprints)
lives in the versioned file's `info` field and the ADF-side artifact manifest.
"""

import json
from pathlib import Path


BENCHMARK_DIR = Path(__file__).parent
DATA_DIR = BENCHMARK_DIR / "data"
SOURCE_FPATH = DATA_DIR / "__NAME___v__VERSION__.jsonl"
OUTPUT_FPATH = DATA_DIR / "__NAME___benchmark.jsonl"
_FIELDS = __FIELDS__


def prepare() -> Path:
    """Materialize canonical rows from the versioned data file (idempotent)."""
    rows = [
        json.loads(line)
        for line in SOURCE_FPATH.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    OUTPUT_FPATH.write_text(
        "".join(
            json.dumps({f: row[f] for f in _FIELDS}, ensure_ascii=False) + "\\n"
            for row in rows
        ),
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} rows to {OUTPUT_FPATH}")
    return OUTPUT_FPATH


if __name__ == "__main__":
    prepare()
'''


def _prepare_py(name: str, version: int) -> str:
    return (_PREPARE_TEMPLATE
            .replace("__FIELDS__", repr(list(_GYM_ITEM_FIELDS)))
            .replace("__NAME__", name)
            .replace("__VERSION__", str(version)))


def _profile_yaml(name: str, version: int, item_count: int) -> str:
    probe = max(1, min(int(item_count), 4))
    return f"""# RSI v0 profile for the {name} benchmark (ADF RSI trajectory synthesis).
# GENERATED by ADF scripts/gym_publish_benchmark.py — regenerate, do not hand-edit.
# Benchmark registered so eval_service can address it; real `gym eval run`
# chain wiring is a later phase (see benchmarks/{name}/config.yaml).
profile_id: rsi-v0-{name}

adapters:
  dsh:
    harness_agent: {name}_dsh_agent
    version: "1"
    config_paths:
      - benchmarks/{name}/config.yaml
    description: >-
      dsh CLI harness wired to the {name} benchmark package (materialized from
      ADF RSI trajectory synthesis; manifest-tracked on the ADF side).

benchmarks:
  {name}:
    dataset_fpath: benchmarks/{name}/data/{name}_v{version}.jsonl
    holdout_dataset_fpath: null
    dataset_version: v{version}
    config_paths: []
    probe_split_size: {probe}

budgets:
  split_eval_soft_limit: 10
  lineage_max_evals: 500
  lineage_max_tokens: 2000000000
"""


def main() -> int:
    ap = argparse.ArgumentParser(description="Publish a synthetic ADF benchmark to the Gym directory")
    ap.add_argument("--gym-root", required=True,
                    help="Gym project root (contains benchmarks/ and eval_service/profiles/)")
    ap.add_argument("--benchmark", default=None,
                    help="Benchmark name (defaults to payload.name)")
    ap.add_argument("--version", type=int, required=True,
                    help="Benchmark artifact version (written to the filename and profile)")
    args = ap.parse_args()

    payload: Dict[str, Any] = json.load(sys.stdin)
    name = _safe_name(str(args.benchmark or payload.get("name") or ""))
    version = int(args.version)
    items = payload.get("items") or []
    if not items:
        print("payload.items is empty: no tasks to publish (explicit failure; do not write an empty benchmark)",
              file=sys.stderr)
        return 2
    for row in items:
        missing = [f for f in _GYM_ITEM_FIELDS if f not in row]
        if missing:
            print(f"item is missing field {missing}: does not conform to the Gym benchmark row specification",
                  file=sys.stderr)
            return 2

    gym_root = Path(args.gym_root).expanduser().resolve()
    bench_dir = gym_root / "benchmarks" / name
    written: List[str] = []

    versioned = bench_dir / "data" / f"{name}_v{version}.jsonl"
    _write(versioned,
           "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in items),
           written, gym_root)
    _write(bench_dir / "config.yaml", _config_yaml(name, version), written, gym_root)
    _write(bench_dir / "prepare.py", _prepare_py(name, version), written, gym_root)
    _write(gym_root / "eval_service" / "profiles" / f"rsi_v0_{name}.yaml",
           _profile_yaml(name, version, len(items)), written, gym_root)

    # Materialize the prepare output (canonical 3-field rows) directly here as well, ensuring prepare.py is idempotent and replayable
    canonical = bench_dir / "data" / f"{name}_benchmark.jsonl"
    _write(canonical,
           "".join(
               json.dumps({f: row[f] for f in _GYM_ITEM_FIELDS}, ensure_ascii=False) + "\n"
               for row in items
           ),
           written, gym_root)

    manifest = payload.get("manifest") or {}
    json.dump({
        "written": written,
        "benchmark": name,
        "version": version,
        "item_count": len(items),
        "generator_code_hash": manifest.get("generator_code_hash"),
        "source_fingerprints": manifest.get("source_fingerprints"),
    }, sys.stdout, ensure_ascii=False, indent=2)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

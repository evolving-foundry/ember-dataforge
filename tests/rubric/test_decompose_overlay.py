"""P3: overlay_decompositions / apply_decompositions_to_scores / ordering_metrics.
Weight-conservation invariant (parent_effective + child_total == parent_weight) and
the delta formula `sum(lambda*w*(coverage - parent_score))/sum(positive weights)` are
checked by hand item by item.
"""
from __future__ import annotations

import pytest

from data_designer.rubric.evolve.decompose import (
    apply_decompositions_to_scores,
    ordering_metrics,
    overlay_decompositions,
)
from data_designer.rubric.protocol.fingerprint import parent_fingerprint
from data_designer.rubric.protocol.schemas import PositiveRefinementProtocolError
from tests.rubric.evolve_fixture import child_for


def _committed_decomposition():
    response_ids = [f"resp-{i}" for i in range(8)]
    children = [child_for(index=index, response_ids=response_ids) for index in range(3)]
    # Child records after registry commit carry rubric_id (generated by
    # _validate_decomposition).
    for index, child in enumerate(children):
        child["rubric_id"] = f"r0:completion:{index:016x}"
    return {
        "parent_rubric_id": "r0",
        "parent_fingerprint": parent_fingerprint("r0", "title r0", "criterion zero", 0.6),
        "parent_title": "title r0",
        "parent_description": "criterion zero",
        "parent_weight": 0.6,
        "blend_lambda": 0.5,
        "children": children,
    }, response_ids


def test_overlay_splits_weight_and_keeps_family_conservation():
    decomposition, _ = _committed_decomposition()
    rubrics = [
        {"rubric_key": "r0", "title": "title r0", "description": "criterion zero", "weight": 0.6},
        {"rubric_key": "r1", "title": "title r1", "description": "criterion one", "weight": 0.4},
    ]
    overlaid, diagnostics = overlay_decompositions(rubrics, [decomposition])
    assert diagnostics == {"overlay_parent_count": 1, "overlay_child_count": 3}
    by_key = {item["rubric_key"]: item for item in overlaid}
    assert len(overlaid) == 5
    parent = by_key["r0"]
    assert parent["weight"] == pytest.approx(0.3)
    assert parent["dcd_role"] == "parent"
    assert parent["dcd_original_weight"] == 0.6
    child_total = sum(
        item["weight"] for item in overlaid if item.get("dcd_role") == "child"
    )
    assert child_total == pytest.approx(0.3)
    assert parent["weight"] + child_total == pytest.approx(0.6)
    for item in overlaid:
        if item.get("dcd_role") == "child":
            assert item["source"] == "dynamic_rubric"
            assert item["dcd_parent_rubric_key"] == "r0"
            assert item["weight"] == pytest.approx(0.1)


def test_overlay_rejects_drifted_parent_and_absent_parent():
    decomposition, _ = _committed_decomposition()
    drifted_weight = [
        {"rubric_key": "r0", "title": "title r0", "description": "criterion zero", "weight": 0.9}
    ]
    with pytest.raises(PositiveRefinementProtocolError, match="no longer matches"):
        overlay_decompositions(drifted_weight, [decomposition])
    drifted_text = [
        {"rubric_key": "r0", "title": "rewritten title", "description": "criterion zero", "weight": 0.6}
    ]
    with pytest.raises(PositiveRefinementProtocolError, match="semantics changed"):
        overlay_decompositions(drifted_text, [decomposition])
    with pytest.raises(PositiveRefinementProtocolError, match="absent from current query rubrics"):
        overlay_decompositions([], [decomposition])


def _evidence(response_ids, *, parent_score):
    rows = {}
    for position, response_id in enumerate(response_ids):
        rows[response_id] = {
            "rubric_ids": ["r0", "r1"],
            "rubric_scores": [parent_score[position], 0],
            "rubric_weights": [0.6, 0.4],
        }
    return rows


def test_apply_decompositions_delta_matches_hand_computation():
    decomposition, response_ids = _committed_decomposition()
    children = decomposition["children"]
    # child 0: resp0..2 pass; child 1: resp3..5; child 2: resp6..7 + resp0
    child_for_0 = children[0]
    child_for_1 = children[1]
    child_for_2 = children[2]
    patterns = {
        "child0": [1, 1, 1, 0, 0, 0, 0, 0],
        "child1": [0, 0, 0, 1, 1, 1, 0, 0],
        "child2": [1, 0, 0, 0, 0, 0, 1, 1],
    }
    for child, pattern in zip((child_for_0, child_for_1, child_for_2), patterns.values()):
        for row, value in zip(child["judge_scores"], pattern):
            row["score"] = value
        child["pass_count"] = sum(pattern)
    # parent scores: resp0=1, resp1=0 -> non-zero difference between coverage and
    # parent_score
    evidence = _evidence(response_ids, parent_score=[1, 0, 0, 0, 0, 0, 0, 0])
    results = apply_decompositions_to_scores(evidence, [decomposition])
    for index, response_id in enumerate(response_ids):
        coverage = (patterns["child0"][index] + patterns["child1"][index] + patterns["child2"][index]) / 3
        parent_score = evidence[response_id]["rubric_scores"][0]
        # denominator = sum of positive weights = 0.6 + 0.4 = 1.0
        expected_delta = 0.5 * 0.6 * (coverage - parent_score) / 1.0
        row = results[response_id]
        assert row["delta"] == pytest.approx(expected_delta)
        assert row["original_reward"] == pytest.approx(parent_score * 0.6 / 1.0)
        assert row["combined_reward"] == pytest.approx(row["original_reward"] + expected_delta)
        assert row["completion_coverage"] == pytest.approx(coverage)
        assert row["dcd_reward_delta"] == row["delta"]
        assert row["dcd_combined_reward"] == row["combined_reward"]
        assert row["parent_share"] == 0.5 and row["child_share"] == 0.5


def test_apply_decompositions_rejects_misaligned_evidence():
    decomposition, response_ids = _committed_decomposition()
    evidence = _evidence(response_ids, parent_score=[0] * 8)
    evidence[response_ids[0]]["rubric_ids"] = ["r0"]
    with pytest.raises(PositiveRefinementProtocolError, match="misaligned"):
        apply_decompositions_to_scores(evidence, [decomposition])
    partial = {response_id: value for response_id, value in evidence.items() if response_id != response_ids[0]}
    with pytest.raises(PositiveRefinementProtocolError, match="frozen source group"):
        apply_decompositions_to_scores(partial, [decomposition])


def test_ordering_metrics_counts_reversals_and_sign_flips():
    metrics = ordering_metrics([0.1, 0.5, 0.9], [0.9, 0.5, 0.1])
    assert metrics == {
        "order_reversal_count": 3,
        "comparable_pair_count": 3,
        "sign_flip_count": 2,
    }
    identity = ordering_metrics([0.2, 0.4, 0.6], [0.2, 0.4, 0.6])
    assert identity["order_reversal_count"] == 0
    assert identity["sign_flip_count"] == 0
    with pytest.raises(PositiveRefinementProtocolError, match="aligned"):
        ordering_metrics([0.1], [0.1, 0.2])

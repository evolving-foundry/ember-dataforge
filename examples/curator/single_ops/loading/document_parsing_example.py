#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
DocumentParsingOperation example script

Function:
    Automatically generate docx/xlsx/pdf samples, parse them with DocumentParsingOperation into
    C-IR-2 (parsed-doc-v2) rows, and write JSONL.

Run:
    python examples/curator/single_ops/loading/document_parsing_example.py
    python examples/curator/single_ops/loading/document_parsing_example.py --input-dir /path/to/docs

Dependencies:
    pip install -e ".[docs]"
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from datetime import date
from pathlib import Path
from typing import Any, Iterable, List, Mapping, Optional

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parents[3]
sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(PROJECT_ROOT / "examples" / "curator"))

from curator.checkpoint.checkpoint_models import CheckpointConfig
from curator.core.pipeline import MultimodalPipeline
from curator.operations.loading import DocumentParsingOperation
from common import init_ray, shutdown_ray

_NO_CHECKPOINT = CheckpointConfig(enabled=False)
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "data" / "output" / "document_parsing"
_DOCS_MODULES = ("docx", "openpyxl", "pdfplumber", "defusedxml")


def _ensure_docs_dependencies() -> None:
    missing = [name for name in _DOCS_MODULES if importlib.util.find_spec(name) is None]
    if missing:
        raise SystemExit(
            "Document parsing dependencies are missing: "
            + ", ".join(missing)
            + '\nRun: pip install -e ".[docs]"'
        )


def _write_docx(path: Path) -> None:
    from docx import Document

    document = Document()
    document.add_heading("采购结算报告（示例）", level=1)
    document.add_paragraph("本文件由文档解析算子示例脚本自动生成。")
    document.add_paragraph("用于验证标题、正文、表格、合并单元格和中文语言识别。")

    table = document.add_table(rows=3, cols=3)
    table.style = "Table Grid"
    merged = table.cell(0, 0).merge(table.cell(0, 2))
    merged.text = "采购订单汇总"
    headers = ("订单编号", "供应商", "金额")
    values = ("PO-2026-001", "北京星河科技有限公司", "128560.00")
    for index, value in enumerate(headers):
        table.cell(1, index).text = value
    for index, value in enumerate(values):
        table.cell(2, index).text = value
    document.save(str(path))


def _write_xlsx(path: Path) -> None:
    from openpyxl import Workbook

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "采购明细"
    sheet.merge_cells("A1:E1")
    sheet["A1"] = "2026 年采购明细（示例）"
    sheet.append(["订单编号", "供应商", "下单日期", "数量", "金额"])
    sheet.append(["PO-2026-001", "北京星河科技有限公司", date(2026, 10, 1), 2, 128560])
    sheet.append(["PO-2026-002", "上海云帆信息有限公司", date(2026, 10, 8), 1, 86400])
    sheet["F2"] = "=D2*E2"
    sheet["F3"] = "=D3*E3"

    summary = workbook.create_sheet("汇总")
    summary.append(["供应商", "已付款金额"])
    summary.append(["北京星河科技有限公司", 128560])
    summary.append(["上海云帆信息有限公司", 86400])
    workbook.save(str(path))


def _write_pdf(path: Path) -> None:
    lines = (
        "Document Parsing Example",
        "This PDF is generated by the example script.",
        "Native PDF text is extracted with pdfplumber.",
        "Scanned PDFs should use image_ocr instead.",
    )
    commands: List[str] = []
    y = 760
    for line in lines:
        encoded = line.encode("latin-1").hex()
        commands.append(f"BT /F1 12 Tf 72 {y} Td <{encoded}> Tj ET")
        y -= 22
    content = "\n".join(commands).encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length " + str(len(content)).encode("ascii") + b" >>\nstream\n"
        + content + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    header = b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"
    body = b""
    offsets = [0]
    for number, obj in enumerate(objects, start=1):
        offsets.append(len(header) + len(body))
        body += f"{number} 0 obj\n".encode("ascii") + obj + b"\nendobj\n"
    xref_offset = len(header) + len(body)
    xref = b"xref\n0 6\n0000000000 65535 f \n"
    for offset in offsets[1:]:
        xref += f"{offset:010d} 00000 n \n".encode("ascii")
    trailer = (
        b"trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n"
        + str(xref_offset).encode("ascii")
        + b"\n%%EOF\n"
    )
    path.write_bytes(header + body + xref + trailer)


def _jsonable(value: Any) -> Any:
    if hasattr(value, "model_dump"):
        return value.model_dump(mode="json", exclude_none=False)
    if isinstance(value, Mapping):
        return {key: _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    return value


def _write_jsonl(path: Path, rows: Iterable[Mapping[str, Any]]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(
                json.dumps(_jsonable(row), ensure_ascii=False, separators=(",", ":"))
            )
            handle.write("\n")


def _print_rows(rows: Iterable[Mapping[str, Any]]) -> None:
    for index, row in enumerate(rows, start=1):
        error = row.get("error")
        if error:
            print(f"  Record {index}: failed {error.get('code')} ({error.get('stage')})")
            continue
        document = row.get("parsed_doc") or {}
        media_type = document.get("source", {}).get("media_type", "unknown")
        blocks = document.get("blocks", [])
        tables = sum(block.get("type") == "table" for block in blocks)
        print(
            f"  Record {index}: {media_type}, language={document.get('language')}, "
            f"blocks={len(blocks)}, tables={tables}"
        )


def run_example(input_dir: Optional[Path], output_dir: Path, create_samples: bool) -> int:
    _ensure_docs_dependencies()
    output_dir.mkdir(parents=True, exist_ok=True)
    if input_dir is None:
        input_dir = output_dir / "inputs"
    input_dir = input_dir.resolve()
    input_dir.mkdir(parents=True, exist_ok=True)

    if create_samples:
        _write_docx(input_dir / "procurement_settlement_report_example.docx")
        _write_xlsx(input_dir / "procurement_details_example.xlsx")
        _write_pdf(input_dir / "document_parsing_example.pdf")
        print(f"Generated example documents: {input_dir}")

    if not init_ray():
        raise SystemExit("Ray initialization failed; cannot run the example")

    output_file = output_dir / "parsed-documents.jsonl"
    pipeline = MultimodalPipeline(enable_tracking=False, checkpoint_config=_NO_CHECKPOINT)
    try:
        pipeline.add_operation(
            DocumentParsingOperation(
                {
                    "data_paths": [str(input_dir)],
                    "allowed_roots": [str(input_dir)],
                    "extract_style": True,
                    "on_error": "skip",
                }
            )
        )
        result = pipeline.run()
        rows = [_jsonable(row) for row in result.dataset.iter_rows()]
        _write_jsonl(output_file, rows)
        print(f"Parsing complete: {len(rows)} records")
        _print_rows(rows)
        print(f"Output file: {output_file}")
        return 0
    except Exception as exc:
        code = getattr(exc, "code", None)
        message = getattr(exc, "message", str(exc))
        print(f"Execution failed: {code or type(exc).__name__}: {message}")
        return 1
    finally:
        pipeline.cleanup()
        shutdown_ray()


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="DocumentParsingOperation example")
    parser.add_argument(
        "--input-dir",
        type=Path,
        default=None,
        help="Directory to parse; when omitted, generates docx/xlsx/pdf samples in the output directory",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="JSONL output directory",
    )
    parser.add_argument(
        "--no-sample",
        action="store_true",
        help="Reuse existing files in inputs/ under the output directory instead of regenerating samples",
    )
    args = parser.parse_args(argv)
    create_samples = args.input_dir is None and not args.no_sample
    return run_example(args.input_dir, args.output_dir, create_samples)


if __name__ == "__main__":
    raise SystemExit(main())
